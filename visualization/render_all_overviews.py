#!/usr/bin/env python3
"""
Batch-generate ONLY two overview figures per case:

1) <case>_RAS_overview_tn_vs_cropped_aligned.png
2) <case>_RAS_overview_tn_vs_regwarped_aligned_MRA.png

It calls code/visualization/render_case_ipl_view.py twice per case and then copies ONLY
the overview PNGs into --out-dir.

Default assumptions based on your repo:
- index: results/labels/tn_centroids_index.csv  (has case_id, side, ...)
- cropped MRI nifti: data/preprocessed_cropped/mri/<case>.nii.gz
- warped MRA nifti: outputs/MRIfixed_MRAmoving/ANTs_result/warped/<case>_reg_Warped.nii.gz
- TN seg root: 2020-22_MRIs_Cropped_and_Segmentations
"""

from __future__ import annotations

import argparse
import csv
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Iterable, List, Tuple


def read_case_ids_from_index(index_csv: Path) -> List[str]:
    if not index_csv.exists():
        raise FileNotFoundError(f"index csv not found: {index_csv}")

    case_ids: List[str] = []
    with index_csv.open("r", newline="") as f:
        reader = csv.DictReader(f)
        if "case_id" not in reader.fieldnames:
            raise ValueError(f"index csv missing 'case_id' column. got: {reader.fieldnames}")
        for row in reader:
            cid = (row.get("case_id") or "").strip()
            if cid:
                case_ids.append(cid)

    # dedup preserving order
    seen = set()
    out = []
    for c in case_ids:
        if c not in seen:
            seen.add(c)
            out.append(c)
    return out


def run_cmd(cmd: List[str]) -> Tuple[int, str]:
    """
    Run command, return (returncode, merged_output).
    """
    p = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    return p.returncode, p.stdout


def copy_overview_png(reg_root: Path, case_id: str, view_tag: str, suffix: str, out_dir: Path) -> Path:
    """
    Source file is generated by render_case_ipl_view.py:
      <reg_root>/preview_<case>/standardized/<case>_<VIEW>_overview_<suffix>.png
    where the script builds suffix = "_" + args.suffix internally.
    So we pass suffix already WITHOUT leading underscore (e.g. "tn_vs_cropped_aligned"),
    and we locate:
      <case>_<VIEW>_overview_<suffix>.png
    """
    src = reg_root / f"preview_{case_id}" / "standardized" / f"{case_id}_{view_tag}_overview_{suffix}.png"
    if not src.exists():
        raise FileNotFoundError(f"overview png not found after rendering: {src}")

    out_dir.mkdir(parents=True, exist_ok=True)
    dst = out_dir / src.name
    shutil.copy2(src, dst)
    return dst


def cleanup_preview(reg_root: Path, case_id: str) -> None:
    """
    Remove the preview_<case> folder to save space.
    """
    p = reg_root / f"preview_{case_id}"
    if p.exists():
        shutil.rmtree(p)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True, help="Repo root, e.g. /path/to/TN_Reg")
    ap.add_argument(
        "--index",
        default="results/labels/tn_centroids_index.csv",
        help="Centroid index csv relative to --root (default: results/labels/tn_centroids_index.csv)",
    )
    ap.add_argument(
        "--tn-seg-root",
        default="2020-22_MRIs_Cropped_and_Segmentations",
        help="TN seg root relative to --root",
    )
    ap.add_argument(
        "--cropped-mri-dir",
        default="data/preprocessed_cropped/mri",
        help="Directory containing cropped MRI niftis relative to --root",
    )
    ap.add_argument(
        "--warped-mra-dir",
        default="outputs/MRIfixed_MRAmoving/ANTs_result/warped",
        help="Directory containing warped MRA niftis relative to --root",
    )
    ap.add_argument(
        "--render-script",
        default="code/visualization/render_case_ipl_view.py",
        help="Render script path relative to --root",
    )
    ap.add_argument(
        "--out-dir",
        default="figures/ANTs",
        help="Output directory (relative to --root) to store ONLY the overview PNGs",
    )

    # fixed view params (your verified “golden” settings)
    ap.add_argument("--view", default="ras", choices=["ras", "ipl"])
    ap.add_argument("--ras-rotate-180", action="store_true", default=True)
    ap.add_argument("--align-lower-to-upper", action="store_true", default=True)
    ap.add_argument("--centroid-space", default="raw", choices=["raw", "source", "auto"])
    ap.add_argument("--shift-dz", type=float, default=-1.0)
    ap.add_argument("--shift-dy", type=float, default=-1.0)
    ap.add_argument("--shift-dx", type=float, default=-1.0)

    # optional knobs
    ap.add_argument("--python", default=sys.executable, help="Python executable to run render script")
    ap.add_argument("--keep-preview", action="store_true", help="Keep preview_<case> folders (default: delete)")
    ap.add_argument("--limit", type=int, default=0, help="If >0, only run first N cases (debug)")
    ap.add_argument("--dry-run", action="store_true", help="Print commands but do not execute")

    args = ap.parse_args()

    root = Path(args.root).resolve()
    index_csv = (root / args.index).resolve()
    tn_seg_root = (root / args.tn_seg_root).resolve()
    cropped_mri_dir = (root / args.cropped_mri_dir).resolve()
    warped_mra_dir = (root / args.warped_mra_dir).resolve()
    render_script = (root / args.render_script).resolve()
    out_dir = (root / args.out_dir).resolve()

    if not render_script.exists():
        raise FileNotFoundError(f"render script not found: {render_script}")
    if not tn_seg_root.exists():
        raise FileNotFoundError(f"tn seg root not found: {tn_seg_root}")
    if not cropped_mri_dir.exists():
        raise FileNotFoundError(f"cropped mri dir not found: {cropped_mri_dir}")
    if not warped_mra_dir.exists():
        raise FileNotFoundError(f"warped mra dir not found: {warped_mra_dir}")

    case_ids = read_case_ids_from_index(index_csv)
    if args.limit and args.limit > 0:
        case_ids = case_ids[: args.limit]

    view_tag = args.view.upper()

    # log files
    out_dir.mkdir(parents=True, exist_ok=True)
    log_path = out_dir / "batch_render_log.txt"
    status_csv = out_dir / "batch_render_status.csv"

    def log(msg: str) -> None:
        print(msg, flush=True)
        with log_path.open("a") as f:
            f.write(msg + "\n")

    log(f"[INFO] cases={len(case_ids)} index={index_csv}")
    log(f"[INFO] out_dir={out_dir}")
    log(f"[INFO] view={args.view} centroid_space={args.centroid_space} shift=({args.shift_dz},{args.shift_dy},{args.shift_dx})")

    # write status header
    with status_csv.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["case_id", "cropped_mri_ok", "warped_mra_ok", "cropped_mri_png", "warped_mra_png", "notes"])

    for i, case_id in enumerate(case_ids, 1):
        notes = []
        cropped_png = ""
        warped_png = ""

        log(f"\n===== [{i}/{len(case_ids)}] case={case_id} =====")

        cropped_mri = cropped_mri_dir / f"{case_id}.nii.gz"
        warped_mra = warped_mra_dir / f"{case_id}_reg_Warped.nii.gz"

        # --- 1) TN vs CROPPED MRI ---
        cropped_ok = False
        if not cropped_mri.exists():
            notes.append(f"missing_cropped_mri:{cropped_mri}")
            log(f"[SKIP] cropped MRI not found: {cropped_mri}")
        else:
            cmd1 = [
                args.python,
                str(render_script),
                "--case-id",
                case_id,
                "--reg-root",
                str(root),
                "--tn-seg-root",
                str(tn_seg_root),
                "--reg-nifti",
                str(cropped_mri),
                "--view",
                args.view,
                "--centroid-space",
                args.centroid_space,
                "--shift-dz",
                str(args.shift_dz),
                "--shift-dy",
                str(args.shift_dy),
                "--shift-dx",
                str(args.shift_dx),
                "--suffix",
                "tn_vs_cropped_aligned",
            ]
            if args.ras_rotate_180:
                cmd1.append("--ras-rotate-180")
            if args.align_lower_to_upper:
                cmd1.append("--align-lower-to-upper")

            log("[CMD] " + " ".join(cmd1))
            if not args.dry_run:
                rc, out = run_cmd(cmd1)
                if rc != 0:
                    notes.append("cropped_mri_render_failed")
                    log("[ERR] render cropped MRI failed:\n" + out)
                else:
                    log("[OK] render cropped MRI done")
                    try:
                        p = copy_overview_png(root, case_id, view_tag, "tn_vs_cropped_aligned", out_dir)
                        cropped_png = str(p)
                        cropped_ok = True
                        log(f"[OK] copied: {p}")
                    except Exception as e:
                        notes.append(f"cropped_mri_copy_failed:{e}")
                        log(f"[ERR] copy cropped overview failed: {e}")

        # --- 2) TN vs WARPED MRA ---
        warped_ok = False
        if not warped_mra.exists():
            notes.append(f"missing_warped_mra:{warped_mra}")
            log(f"[SKIP] warped MRA not found: {warped_mra}")
        else:
            cmd2 = [
                args.python,
                str(render_script),
                "--case-id",
                case_id,
                "--reg-root",
                str(root),
                "--tn-seg-root",
                str(tn_seg_root),
                "--reg-nifti",
                str(warped_mra),
                "--view",
                args.view,
                "--centroid-space",
                args.centroid_space,
                "--shift-dz",
                str(args.shift_dz),
                "--shift-dy",
                str(args.shift_dy),
                "--shift-dx",
                str(args.shift_dx),
                "--suffix",
                "tn_vs_regwarped_aligned_MRA",
            ]
            if args.ras_rotate_180:
                cmd2.append("--ras-rotate-180")
            if args.align_lower_to_upper:
                cmd2.append("--align-lower-to-upper")

            log("[CMD] " + " ".join(cmd2))
            if not args.dry_run:
                rc, out = run_cmd(cmd2)
                if rc != 0:
                    notes.append("warped_mra_render_failed")
                    log("[ERR] render warped MRA failed:\n" + out)
                else:
                    log("[OK] render warped MRA done")
                    try:
                        p = copy_overview_png(root, case_id, view_tag, "tn_vs_regwarped_aligned_MRA", out_dir)
                        warped_png = str(p)
                        warped_ok = True
                        log(f"[OK] copied: {p}")
                    except Exception as e:
                        notes.append(f"warped_mra_copy_failed:{e}")
                        log(f"[ERR] copy warped overview failed: {e}")

        # cleanup preview folder to keep only the two overview pngs in figures/ANTs
        if (not args.keep_preview) and (not args.dry_run):
            cleanup_preview(root, case_id)
            log("[INFO] cleaned preview folder")

        # write status row
        with status_csv.open("a", newline="") as f:
            w = csv.writer(f)
            w.writerow([case_id, int(cropped_ok), int(warped_ok), cropped_png, warped_png, "|".join(notes)])

    log("\n[DONE] batch finished.")
    log(f"[DONE] status_csv={status_csv}")
    log(f"[DONE] log_path={log_path}")
    log(f"[DONE] figures={out_dir}")


if __name__ == "__main__":
    main()
