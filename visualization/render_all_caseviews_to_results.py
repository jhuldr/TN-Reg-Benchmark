#!/usr/bin/env python3
"""
Batch render TN case RAS overviews for BOTH:
  (A) MRI cropped  — verify TN alignment in MRI space
  (B) MRA warped   — verify registration quality + MRI-vs-MRA compare

For each case_id we call render_case_ipl_view.py twice:
  1) MRI:  --reg-nifti <mri_cropped>  --suffix <mri_suffix>
  2) MRA:  --reg-nifti <mra_warped>   --suffix <mra_suffix>  --compare-nifti <mri_cropped>

Uses --out-dir so outputs go directly into per-case folders
(no preview_<case> folders are created).

Output per case (e.g. results/visualizations/caseview/<CASE_ID>/):
  MRI:
    <CASE_ID>_ipsi_RAS_tn_vs_cropped_aligned.png
    <CASE_ID>_contra_RAS_tn_vs_cropped_aligned.png
    <CASE_ID>_RAS_overview_tn_vs_cropped_aligned.png
    <CASE_ID>_RAS_manifest_tn_vs_cropped_aligned.txt
  MRA:
    <CASE_ID>_ipsi_RAS_tn_vs_regwarped_aligned_MRA.png
    <CASE_ID>_contra_RAS_tn_vs_regwarped_aligned_MRA.png
    <CASE_ID>_RAS_overview_tn_vs_regwarped_aligned_MRA.png
    <CASE_ID>_RAS_manifest_tn_vs_regwarped_aligned_MRA.txt
  Compare (MRI vs MRA, generated by the MRA run):
    <CASE_ID>_ipsi_RAS_mri_vs_mra_tn_vs_regwarped_aligned_MRA.png
    <CASE_ID>_contra_RAS_mri_vs_mra_tn_vs_regwarped_aligned_MRA.png
"""

from __future__ import annotations

import argparse
import subprocess
from concurrent.futures import ProcessPoolExecutor, as_completed
from datetime import datetime
from pathlib import Path

from tqdm import tqdm


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def ensure_dir(p: Path) -> None:
    p.mkdir(parents=True, exist_ok=True)


def case_id_from_warped(p: Path, suffix: str = "_reg_Warped.nii.gz") -> str:
    name = p.name
    if name.endswith(suffix):
        return name[: -len(suffix)]
    raise ValueError(f"File does not end with {suffix}: {p}")

def resolve_nii(dir_path: Path, case_id: str) -> Path | None:
    for ext in (".nii.gz", ".nii"):
        p = dir_path / f"{case_id}{ext}"
        if p.exists():
            return p
    return None


def run_cmd(cmd: list[str], log_path: Path) -> int:
    ensure_dir(log_path.parent)
    with open(log_path, "w") as f:
        f.write("COMMAND:\n" + " ".join(cmd) + "\n\n")
        f.flush()
        p = subprocess.run(cmd, stdout=f, stderr=subprocess.STDOUT)
    return p.returncode


# ---------------------------------------------------------------------------
# Per-case worker
# ---------------------------------------------------------------------------

def run_one_case(job: tuple) -> tuple[str, str, str]:
    (
        case_id,
        reg_root,
        tn_seg_root,
        raw_dicom_root,
        render_script,
        python_bin,
        mri_nifti,
        mra_warped,
        out_case_dir,
        log_dir,
        shift_dz,
        shift_dy,
        shift_dx,
        mri_suffix,
        mra_suffix,
        skip_done,
        raw_series_max_depth,
        raw_series_min_files,
        raw_series_min_bytes,
    ) = job

    reg_root       = Path(reg_root)
    tn_seg_root    = Path(tn_seg_root)
    raw_dicom_root = Path(raw_dicom_root)
    render_script  = Path(render_script)
    mri_nifti      = Path(mri_nifti)
    mra_warped     = Path(mra_warped)
    out_case_dir   = Path(out_case_dir)
    log_dir        = Path(log_dir)

    # ── Skip check (before creating any dirs) ──
    want_mri_overview = out_case_dir / f"{case_id}_RAS_overview_{mri_suffix}.png"
    want_mra_overview = out_case_dir / f"{case_id}_RAS_overview_{mra_suffix}.png"
    want_cmp_ipsi     = out_case_dir / f"{case_id}_ipsi_RAS_mri_vs_mra_{mra_suffix}.png"
    want_cmp_contra   = out_case_dir / f"{case_id}_contra_RAS_mri_vs_mra_{mra_suffix}.png"

    if skip_done and all(p.exists() for p in [want_mri_overview, want_mra_overview, want_cmp_ipsi, want_cmp_contra]):
        return case_id, "SKIP_DONE", str(out_case_dir)

    # ── Sanity ──
    if not mri_nifti.exists():
        return case_id, "FAIL", f"MRI missing: {mri_nifti}"
    if not mra_warped.exists():
        return case_id, "FAIL", f"MRA warped missing: {mra_warped}"

    # Now create dirs
    ensure_dir(out_case_dir)
    ensure_dir(log_dir)

    # ── Shared args ──
    common = [
        python_bin,
        str(render_script),
        "--case-id",          case_id,
        "--reg-root",         str(reg_root),
        "--tn-seg-root",      str(tn_seg_root),
        "--raw-dicom-root",   str(raw_dicom_root),
        "--out-dir",          str(out_case_dir),
        "--view",             "ras",
        "--ras-rotate-180",
        "--align-lower-to-upper",
        "--centroid-space",   "raw",
        "--shift-dz",         str(shift_dz),
        "--shift-dy",         str(shift_dy),
        "--shift-dx",         str(shift_dx),
    ]

    # Optional raw-series knobs
    if raw_series_max_depth is not None:
        common += ["--raw-series-max-depth", str(raw_series_max_depth)]
    if raw_series_min_files is not None:
        common += ["--raw-series-min-files", str(raw_series_min_files)]
    if raw_series_min_bytes is not None:
        common += ["--raw-series-min-bytes", str(raw_series_min_bytes)]

    ts = datetime.now().strftime("%Y%m%d_%H%M%S")

    # ── 1) MRI cropped ──
    cmd_mri = common + [
        "--reg-nifti", str(mri_nifti),
        "--suffix",    mri_suffix,
    ]
    rc = run_cmd(cmd_mri, log_dir / f"{case_id}_mri_{ts}.log")
    if rc != 0:
        return case_id, "FAIL_MRI", str(log_dir / f"{case_id}_mri_{ts}.log")

    # ── 2) MRA warped ──
    cmd_mra = common + [
        "--reg-nifti",     str(mra_warped),
        "--suffix",        mra_suffix,
        "--compare-nifti", str(mri_nifti),
    ]
    rc = run_cmd(cmd_mra, log_dir / f"{case_id}_mra_{ts}.log")
    if rc != 0:
        return case_id, "FAIL_MRA", str(log_dir / f"{case_id}_mra_{ts}.log")

    # ── Verify key outputs ──
    if not want_mri_overview.exists() or not want_mra_overview.exists():
        return case_id, "FAIL_NO_OUTPUT", str(out_case_dir)

    return case_id, "OK", str(out_case_dir)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser(
        description="Batch render MRI + MRA + compare caseviews (no preview_ folders)."
    )

    # Required
    ap.add_argument("--reg-root",    required=True)
    ap.add_argument("--tn-seg-root", required=True)
    ap.add_argument("--warped-dir",  required=True,
                    help="Directory containing *_reg_Warped.nii.gz (MRA warped)")
    ap.add_argument("--warped-suffix", default="_reg_Warped.nii.gz",
                    help="Suffix of warped files, e.g. _reg_Warped.nii.gz or _prealigned_mra.nii.gz")
    # Input directories
    ap.add_argument("--mri-dir", default="data/preprocessed_cropped/mri",
                    help="MRI cropped nifti dir (relative to reg-root, or absolute)")
    ap.add_argument("--raw-dicom-root", default=None)
    ap.add_argument("--raw-reg-root",   default=None,
                    help="Legacy alias for --raw-dicom-root")

    # Render script
    ap.add_argument("--render-script", default="code/visualization/render_case_ipl_view.py")
    ap.add_argument("--python", default="python")

    # Render params
    ap.add_argument("--shift-dz", type=float, default=-1.0)
    ap.add_argument("--shift-dy", type=float, default=-1.0)
    ap.add_argument("--shift-dx", type=float, default=-1.0)

    # Suffixes
    ap.add_argument("--mri-suffix", default="tn_vs_cropped_aligned")
    ap.add_argument("--mra-suffix", default="tn_vs_regwarped_aligned_MRA")

    # Execution
    ap.add_argument("--nproc",     type=int, default=16)
    ap.add_argument("--skip-done", action="store_true")
    ap.add_argument("--only-case", default=None)

    # Output
    ap.add_argument("--out-dir", default="results/visualizations/caseview")
    ap.add_argument("--log-dir", default="results/visualizations/caseview/_logs")

    # Raw series knobs (passed through to render_case_ipl_view.py)
    ap.add_argument("--raw-series-max-depth", type=int, default=None)
    ap.add_argument("--raw-series-min-files", type=int, default=None)
    ap.add_argument("--raw-series-min-bytes", type=int, default=None)

    args = ap.parse_args()

    # ── Resolve paths ──
    reg_root    = Path(args.reg_root).resolve()
    tn_seg_root = Path(args.tn_seg_root).resolve()
    warped_dir  = Path(args.warped_dir).resolve()

    def resolve_relative(p_str: str) -> Path:
        p = Path(p_str)
        return p.resolve() if p.is_absolute() else (reg_root / p).resolve()

    mri_dir      = resolve_relative(args.mri_dir)
    out_dir_root = resolve_relative(args.out_dir)
    log_dir      = resolve_relative(args.log_dir)

    raw_dicom_root = args.raw_dicom_root or args.raw_reg_root
    if not raw_dicom_root:
        raise SystemExit("ERROR: provide --raw-dicom-root (or --raw-reg-root).")
    raw_dicom_root = resolve_relative(raw_dicom_root)

    render_script = resolve_relative(args.render_script)

    ensure_dir(out_dir_root)
    ensure_dir(log_dir)

    # ── Discover cases ──
    warped_files = sorted(warped_dir.glob(f"*{args.warped_suffix}"))
    if args.only_case:
        warped_files = [p for p in warped_files if case_id_from_warped(p) == args.only_case]

    if not warped_files:
        raise FileNotFoundError(f"No *_reg_Warped.nii.gz in: {warped_dir}")

    jobs = []
    missing = 0

    for wf in warped_files:
        cid = case_id_from_warped(wf, args.warped_suffix)
        mri_nifti = resolve_nii(mri_dir, cid)
        if mri_nifti is None:
            missing += 1
            continue

        jobs.append((
            cid,
            str(reg_root),
            str(tn_seg_root),
            str(raw_dicom_root),
            str(render_script),
            args.python,
            str(mri_nifti),
            str(wf),
            str(out_dir_root / cid),
            str(log_dir),
            args.shift_dz,
            args.shift_dy,
            args.shift_dx,
            args.mri_suffix,
            args.mra_suffix,
            args.skip_done,
            args.raw_series_max_depth,
            args.raw_series_min_files,
            args.raw_series_min_bytes,
        ))

    # ── Print info ──
    print(f"{'=' * 60}")
    print(f"Batch Render: MRI + MRA + Compare (no preview_ folders)")
    print(f"{'=' * 60}")
    print(f"  Warped cases found:   {len(warped_files)}")
    print(f"  Runnable (MRI+MRA):   {len(jobs)}")
    print(f"  Missing MRI:          {missing}")
    print(f"  Warped dir:           {warped_dir}")
    print(f"  MRI dir:              {mri_dir}")
    print(f"  Raw DICOM root:       {raw_dicom_root}")
    print(f"  Output root:          {out_dir_root}")
    print(f"  Log dir:              {log_dir}")
    print(f"  Parallel:             {args.nproc}")
    print(f"  MRI suffix:           {args.mri_suffix}")
    print(f"  MRA suffix:           {args.mra_suffix}")
    print(f"  Skip done:            {args.skip_done}")
    print(f"{'=' * 60}")

    # ── Run ──
    ok = skip = fail = 0

    with ProcessPoolExecutor(max_workers=args.nproc) as ex:
        futures = [ex.submit(run_one_case, j) for j in jobs]
        with tqdm(total=len(futures), desc="Render MRI+MRA+compare", dynamic_ncols=True) as pbar:
            for fut in as_completed(futures):
                cid, status, info = fut.result()
                if status == "OK":
                    ok += 1
                    pbar.set_postfix_str(f"OK {cid}")
                elif status == "SKIP_DONE":
                    skip += 1
                    pbar.set_postfix_str(f"SKIP {cid}")
                else:
                    fail += 1
                    pbar.set_postfix_str(f"{status} {cid}")
                pbar.update(1)

    print(f"\n{'=' * 60}")
    print(f"SUMMARY")
    print(f"{'=' * 60}")
    print(f"  OK:        {ok}")
    print(f"  SKIP_DONE: {skip}")
    print(f"  FAIL:      {fail}")
    print(f"  Outputs:   {out_dir_root}")
    print(f"  Logs:      {log_dir}")


if __name__ == "__main__":
    main()